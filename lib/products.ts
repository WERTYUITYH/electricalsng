export function formatPrice(product: Pick<Product, "sellingPrice" | "referencePrice" | "referencePriceHigh">): string {
  const money = (amount: number) => new Intl.NumberFormat("en-NG", { style: "currency", currency: "NGN", maximumFractionDigits: 0 }).format(amount);
  if (product.sellingPrice !== undefined) return money(product.sellingPrice);
  if (!product.referencePrice) return "Price on request";
  return product.referencePriceHigh ? money(product.referencePrice) + " – " + money(product.referencePriceHigh) : money(product.referencePrice);
}
